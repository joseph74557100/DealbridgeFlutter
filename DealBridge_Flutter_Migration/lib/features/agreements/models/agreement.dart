import 'package:cloud_firestore/cloud_firestore.dart';

import '../../../core/utils/app_formatters.dart';

/// Agreement lifecycle values used by the backend.
abstract final class AgreementStatus {
  static const pendingSignature = 'Pending Signature';
  static const signed = 'Signed';
  static const archived = 'Archived';
  static const expired = 'Expired';
}

/// A signature captured for an agreement.
class AgreementSignature {
  const AgreementSignature({
    this.businessId = '',
    this.businessName = '',
    this.signerUserId = '',
    this.signedDate = '',
    this.signedTime = '',
    this.signature = '',
  });

  final String businessId;
  final String businessName;
  final String signerUserId;
  final String signedDate;
  final String signedTime;
  final String signature;

  factory AgreementSignature.fromMap(Map<String, dynamic> data) {
    return AgreementSignature(
      businessId: (data['businessId'] ?? '').toString(),
      businessName: (data['businessName'] ?? '').toString(),
      signerUserId: (data['signerUserId'] ?? '').toString(),
      signedDate: (data['signedDate'] ?? '').toString(),
      signedTime: (data['signedTime'] ?? '').toString(),
      signature: (data['signature'] ?? '').toString(),
    );
  }
}

/// The `agreements/{agreementId}` document.
///
/// Agreements are generated by the trusted backend when both parties confirm
/// a deal. Clients may only update whitelisted metadata fields.
class Agreement {
  const Agreement({
    required this.id,
    this.agreementId = '',
    this.agreementNumber = '',
    this.dealId = '',
    this.title = '',
    this.description = '',
    this.terms = '',
    this.dealValue = '',
    this.requiredSignatures = 0,
    this.expiryDate = '',
    this.businessOneId = '',
    this.businessOneName = '',
    this.businessTwoId = '',
    this.businessTwoName = '',
    this.participantIds = const <String>[],
    this.createdDate = '',
    this.createdAt = 0,
    this.createdBy = '',
    this.serverGenerated = false,
    this.status = AgreementStatus.pendingSignature,
    this.completionStatus = '',
    this.completedAt = 0,
    this.completedDate = '',
    this.senderUid = '',
    this.recipientUid = '',
    this.acceptedAt = 0,
    this.senderAgreedAt = 0,
    this.recipientAgreedAt = 0,
    this.senderConfirmedAt = 0,
    this.recipientConfirmedAt = 0,
    this.fullySigned = false,
    this.locked = false,
    this.signingStarted = false,
    this.signedDate = '',
    this.version = '',
    this.signatures = const <AgreementSignature>[],
    this.contentHash = '',
    this.notes = '',
    this.attachments = const <String>[],
    this.pdfUrl = '',
    this.fileId = '',
    this.fileName = '',
    this.localPdfPath = '',
    this.updatedBy = '',
    this.driveStatus = '',
  });

  final String id;
  final String agreementId;
  final String agreementNumber;
  final String dealId;
  final String title;
  final String description;
  final String terms;
  final String dealValue;
  final int requiredSignatures;
  final String expiryDate;
  final String businessOneId;
  final String businessOneName;
  final String businessTwoId;
  final String businessTwoName;
  final List<String> participantIds;
  final String createdDate;
  final int createdAt;
  final String createdBy;
  final bool serverGenerated;
  final String status;
  final String completionStatus;
  final int completedAt;
  final String completedDate;
  final String senderUid;
  final String recipientUid;
  final int acceptedAt;
  final int senderAgreedAt;
  final int recipientAgreedAt;
  final int senderConfirmedAt;
  final int recipientConfirmedAt;
  final bool fullySigned;
  final bool locked;
  final bool signingStarted;
  final String signedDate;
  final String version;
  final List<AgreementSignature> signatures;
  final String contentHash;
  final String notes;
  final List<String> attachments;
  final String pdfUrl;
  final String fileId;
  final String fileName;
  final String localPdfPath;
  final String updatedBy;
  final String driveStatus;

  bool get isSigned => status == AgreementStatus.signed;

  bool get hasDocument => pdfUrl.isNotEmpty || localPdfPath.isNotEmpty;

  factory Agreement.fromFirestore(DocumentSnapshot<Map<String, dynamic>> doc) {
    final data = doc.data() ?? const <String, dynamic>{};
    final signatures = data['signatures'];
    final attachments = data['attachments'];
    return Agreement(
      id: doc.id,
      agreementId: (data['agreementId'] ?? doc.id).toString(),
      agreementNumber: (data['agreementNumber'] ?? '').toString(),
      dealId: (data['dealId'] ?? '').toString(),
      title: (data['title'] ?? '').toString(),
      description: (data['description'] ?? '').toString(),
      terms: (data['terms'] ?? '').toString(),
      dealValue: (data['dealValue'] ?? '').toString(),
      requiredSignatures: (data['requiredSignatures'] as num?)?.toInt() ?? 0,
      expiryDate: (data['expiryDate'] ?? '').toString(),
      businessOneId: (data['businessOneId'] ?? '').toString(),
      businessOneName: (data['businessOneName'] ?? '').toString(),
      businessTwoId: (data['businessTwoId'] ?? '').toString(),
      businessTwoName: (data['businessTwoName'] ?? '').toString(),
      participantIds: _stringList(data['participantIds']),
      createdDate: (data['createdDate'] ?? '').toString(),
      createdAt: _int(data['createdAt']),
      createdBy: (data['createdBy'] ?? '').toString(),
      serverGenerated: data['serverGenerated'] == true,
      status: (data['status'] ?? AgreementStatus.pendingSignature).toString(),
      completionStatus: (data['completionStatus'] ?? '').toString(),
      completedAt: _int(data['completedAt']),
      completedDate: (data['completedDate'] ?? '').toString(),
      senderUid: (data['senderUid'] ?? '').toString(),
      recipientUid: (data['recipientUid'] ?? '').toString(),
      acceptedAt: _int(data['acceptedAt']),
      senderAgreedAt: _int(data['senderAgreedAt']),
      recipientAgreedAt: _int(data['recipientAgreedAt']),
      senderConfirmedAt: _int(data['senderConfirmedAt']),
      recipientConfirmedAt: _int(data['recipientConfirmedAt']),
      fullySigned: data['fullySigned'] == true,
      locked: data['locked'] == true,
      signingStarted: data['signingStarted'] == true,
      signedDate: (data['signedDate'] ?? '').toString(),
      version: (data['version'] ?? '').toString(),
      signatures: signatures is List
          ? signatures
              .whereType<Map>()
              .map((e) => AgreementSignature.fromMap(e.cast<String, dynamic>()))
              .toList(growable: false)
          : const <AgreementSignature>[],
      contentHash: (data['contentHash'] ?? '').toString(),
      notes: (data['notes'] ?? '').toString(),
      attachments: _stringList(attachments),
      pdfUrl: (data['pdfUrl'] ?? '').toString(),
      fileId: (data['fileId'] ?? '').toString(),
      fileName: (data['fileName'] ?? '').toString(),
      localPdfPath: (data['localPdfPath'] ?? '').toString(),
      updatedBy: (data['updatedBy'] ?? '').toString(),
      driveStatus: (data['driveStatus'] ?? '').toString(),
    );
  }

  /// The readable creation date.
  String? get createdLabel => AppFormatters.fromEpoch(createdAt) ?? createdDate;

  static int _int(dynamic value) {
    if (value is int) return value;
    if (value is num) return value.toInt();
    if (value is Timestamp) return value.toDate().millisecondsSinceEpoch;
    if (value is String) return int.tryParse(value) ?? 0;
    return 0;
  }

  static List<String> _stringList(dynamic value) {
    if (value is List) {
      return value.whereType<String>().toList(growable: false);
    }
    return const <String>[];
  }
}
